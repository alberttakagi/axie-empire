"""Import full attack sequences rendered by tools/sprite-gen
(window.renderAttackSequenceAligned + window.idleSequenceAnchor) into the game.

Input:  tools/sprite-gen/output/unit_<id>[_evolved]_attackanim_<i>.png
        a JSON file of the browser results ({key: {frames, durationMs, anchor,
        size, idleSeq: {anchor, size}}}), path given as argv[1]
Output: public/sprites/units/<key>_<i>.png  (rescaled into the SHIPPED idle
        sequence's pixel space, so attack and idle share one scale)
        src/ATTACK_ANIM_META.js  (anchors the game uses to keep the body put)
Then run:  python3 tools/pack_sequence_atlases.py --delete-frames
"""
import json, os, sys
from PIL import Image

SRC = 'tools/sprite-gen/output'
DST = 'public/sprites/units'
ATLAS = 'public/sprites/atlas'
# Fraction of each clip where the blow lands (casts release a bit later).
IMPACT = {'melee': 0.45, 'cast': 0.5}

results = json.load(open(sys.argv[1]))
anims = json.load(open(sys.argv[2])) if len(sys.argv) > 2 else {}
meta = {}
for key, r in sorted(results.items()):
    base = key[len('unit_'):-len('_attackanim')]  # e.g. basic / basic_evolved
    idle_json = f'{ATLAS}/unit_{base}_idleanim.json'
    frames0 = None
    for tex in json.load(open(idle_json))['textures']:
        for fr in tex['frames']:
            if fr['filename'] == '0':
                frames0 = fr
    src_w, src_h = frames0['sourceSize']['w'], frames0['sourceSize']['h']
    kx = src_w / r['idleSeq']['size']['w']
    ky = src_h / r['idleSeq']['size']['h']
    if abs(kx - ky) > 0.03:
        print(f'WARN {key}: idle scale mismatch kx={kx:.3f} ky={ky:.3f}')
    k = (kx + ky) / 2
    out_w = h = None
    for i in range(r['frames']):
        im = Image.open(f'{SRC}/{key}_{i}.png').convert('RGBA')
        out = im.resize((max(1, round(im.width * k)), max(1, round(im.height * k))), Image.LANCZOS)
        out.save(f'{DST}/{key}_{i}.png')
        out_w, out_h = out.size
    kind = 'cast' if '/cast' in anims.get(key, '') else 'melee'
    meta[base] = {
        'frames': r['frames'],
        'durationMs': r['durationMs'],
        'impact': IMPACT[kind],
        'anchor': {'x': round(r['anchor']['x'] * k, 1), 'y': round(r['anchor']['y'] * k, 1)},
        'size': {'w': out_w, 'h': out_h},
        'idleAnchor': {'x': round(r['idleSeq']['anchor']['x'] * kx, 1), 'y': round(r['idleSeq']['anchor']['y'] * ky, 1)},
        'idleSize': {'w': src_w, 'h': src_h},
    }
    print(f'{key}: {r["frames"]} frames, k={k:.3f}')

with open('src/ATTACK_ANIM_META.js', 'w') as f:
    f.write('// Generated by tools/import_attack_anims.py — do not edit by hand.\n')
    f.write('// Per unit (and _evolved) attack sequence: frame count, clip length,\n')
    f.write('// impact fraction, and where the spine anchor sits in the attack\n')
    f.write('// frames vs the shipped idle frames (all in shipped pixel space).\n')
    f.write('export const ATTACK_ANIM_META = ')
    f.write(json.dumps(meta, indent=2))
    f.write(';\n')
print(f'wrote src/ATTACK_ANIM_META.js ({len(meta)} entries)')
