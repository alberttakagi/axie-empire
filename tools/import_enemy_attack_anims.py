"""Import chimera attack sequences (sprite-gen window.chimeraIdleAndAttack)
and register them against the SHIPPED enemy idle art.

The shipped idle frames were rendered with framings that weren't recorded,
so instead of trusting anchors we register: the probe idle frame (rendered
with the same framing as the attack frames) is matched to shipped idle
frame "0" by alpha bounding box — scale k from the box sizes, offset from
the box corners — and verified by silhouette IoU. The attack frames are then
resized by k, and a common canvas point is located in both, giving the
anchors GameScene needs (same contract as ATTACK_ANIM_META for units).

argv[1]: JSON of browser results {enemyId: {frames, durationMs, anim,
         idleOrigin, attackOrigin}}
Writes public/sprites/enemies/enemy_<id>_attackanim_<i>.png and merges
`enemy_<id>` entries into src/ATTACK_ANIM_META.js.
"""
import json, re, sys
from PIL import Image
sys.path.insert(0, 'tools')
from match_chimeras import atlas_frame, mask, iou

SRC = 'tools/sprite-gen/output'
DST = 'public/sprites/enemies'
REF = (256, 256)  # any fixed canvas point works; both crops share the canvas

results = json.load(open(sys.argv[1]))
meta_path = 'src/ATTACK_ANIM_META.js'
meta = json.loads(re.search(r'= (\{[\s\S]*\});', open(meta_path).read()).group(1))

for eid, r in sorted(results.items()):
    if not isinstance(r, dict) or not r.get('frames'):
        print(f'skip {eid}: {r}')
        continue
    shipped = atlas_frame(f'enemy_{eid}_idleanim')
    probe = Image.open(f'{SRC}/enemy_{eid}_probeidle_0.png').convert('RGBA')
    ms, bs = mask(shipped)
    mp, bp = mask(probe)
    score = iou(ms, mp)
    kx = (bs[2] - bs[0]) / (bp[2] - bp[0])
    ky = (bs[3] - bs[1]) / (bp[3] - bp[1])
    k = (kx + ky) / 2
    dx = bs[0] - k * bp[0]
    dy = bs[3] - k * bp[3]  # align feet (bottom edge) exactly
    flag = '' if score > 0.85 and abs(kx - ky) < 0.06 else '  <-- CHECK'
    print(f'{eid:10s} k={k:.3f} (kx {kx:.3f} ky {ky:.3f}) iou={score:.3f}{flag}')

    out_w = out_h = None
    for i in range(r['frames']):
        im = Image.open(f'{SRC}/enemy_{eid}_attackanim_{i}.png').convert('RGBA')
        out = im.resize((max(1, round(im.width * k)), max(1, round(im.height * k))), Image.LANCZOS)
        out.save(f'{DST}/enemy_{eid}_attackanim_{i}.png')
        out_w, out_h = out.size
    # Common canvas point in each crop's own coordinates.
    pi = (REF[0] - r['idleOrigin']['x'], REF[1] - r['idleOrigin']['y'])
    pa = (REF[0] - r['attackOrigin']['x'], REF[1] - r['attackOrigin']['y'])
    meta[f'enemy_{eid}'] = {
        'frames': r['frames'],
        'durationMs': r['durationMs'],
        'impact': 0.5 if '/ranged/' in (r.get('anim') or '') else 0.45,
        'anchor': {'x': round(pa[0] * k, 1), 'y': round(pa[1] * k, 1)},
        'size': {'w': out_w, 'h': out_h},
        'idleAnchor': {'x': round(pi[0] * k + dx, 1), 'y': round(pi[1] * k + dy, 1)},
        'idleSize': {'w': shipped.width, 'h': shipped.height},
    }

with open(meta_path, 'w') as f:
    f.write('// Generated by tools/import_attack_anims.py + tools/import_enemy_attack_anims.py\n')
    f.write('// — do not edit by hand. Per unit / enemy_<id> attack sequence: frame\n')
    f.write('// count, clip length, impact fraction, and where a shared anchor sits in\n')
    f.write('// the attack frames vs the shipped idle frames (shipped pixel space).\n')
    f.write('export const ATTACK_ANIM_META = ')
    f.write(json.dumps(meta, indent=2))
    f.write(';\n')
print(f'wrote {meta_path} ({len(meta)} entries)')
